"""hotel IDs, staff sign-in codes and hotel-scoped device setup

DECISIONS D82 (user request).
- hotels.code: the hotel's public Hotel ID, `DYN-` and 13 Crockford base32 characters (no I,
  L, O or U, at least one letter), generated by the database for every hotel, unique and
  never changed. Staff type
  it on guest tablets, kitchen displays and the room-service app.
- app.hotel_by_code(text): resolves a Hotel ID before any hotel context exists (definer, like
  app.device_lookup). Returns only the id and status.
- hotel_users.staff_code_hash: SHA-256 of a member's 8-digit staff code with the server pepper,
  unique per hotel. With the Hotel ID and the member's PIN it signs in to room service.
- app.redeem_pairing is dropped: a setup code is now redeemed inside the hotel named by the
  Hotel ID, under that hotel's RLS, after the issuing manager's PIN is checked.
- app.admin_hotels() also returns the Hotel ID, so the admin panel can show and search it.

Revision ID: 0031
Revises: 0030
Create Date: 2026-10-14 09:00
"""

