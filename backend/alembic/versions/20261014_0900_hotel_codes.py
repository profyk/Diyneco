def _admin_hotels(with_code: bool) -> str:
    """app.admin_hotels() as of 0030, optionally with the Hotel ID after the slug."""
    return f"""
        DROP FUNCTION app.admin_hotels();
        CREATE FUNCTION app.admin_hotels()
        RETURNS TABLE (
          id uuid, name text, slug text, {"code text, " if with_code else ""}status text, status_reason text,
          created_at timestamptz, plan_code text, subscription_status text, renews_on date,
          rooms bigint, devices bigint, connected_devices bigint, staff bigint, active_stays bigint,
          last_activity timestamptz
        )
        LANGUAGE sql STABLE SECURITY DEFINER SET search_path = app, extensions, pg_temp AS $$
          SELECT h.id, h.name, h.slug, {"h.code, " if with_code else ""}h.status, h.status_reason, h.created_at,
            p.code, s.status, s.renews_on,
            (SELECT count(*) FROM app.rooms r WHERE r.hotel_id = h.id AND r.deleted_at IS NULL),
            (SELECT count(*) FROM app.devices d WHERE d.hotel_id = h.id AND d.status <> 'revoked'),
            (SELECT count(*) FROM app.devices d WHERE d.hotel_id = h.id AND d.status <> 'revoked'
               AND d.last_seen_at > now() - interval '5 minutes'),
            (SELECT count(*) FROM app.hotel_users u WHERE u.hotel_id = h.id AND u.status = 'active'),
            (SELECT count(*) FROM app.stays st WHERE st.hotel_id = h.id
               AND st.status IN ('checked_in','active','checkout_pending')),
            (SELECT max(e.created_at) FROM app.event_outbox e WHERE e.hotel_id = h.id)
          FROM app.hotels h
          LEFT JOIN app.subscriptions s ON s.hotel_id = h.id AND s.status IN ({CURRENT_STATUSES})
          LEFT JOIN app.plans p ON p.id = s.plan_id
          ORDER BY h.created_at DESC
        $$;
        REVOKE ALL ON FUNCTION app.admin_hotels() FROM PUBLIC;
        GRANT EXECUTE ON FUNCTION app.admin_hotels() TO diyneco_api, diyneco_platform;
    """


